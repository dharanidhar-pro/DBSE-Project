/**
 * Returns the dedicated, accurate product photo URL for a given product_id
 */
export const getProductImageUrl = (productId: number, category?: string, customImages?: string[]): string => {
  if (customImages && customImages.length > 0 && customImages[0]?.trim()) {
    return customImages[0];
  }
  if (productImages[productId]) {
    return productImages[productId];
  }
  if (category && categoryFallbackImages[category]) {
    return categoryFallbackImages[category];
  }
  return 'https://images.unsplash.com/photo-1505740420928-5e560c06d30e?w=800&auto=format&fit=crop&q=80';
};

/**
 * Returns an array of multiple image URLs for a product gallery
 */
export const getProductImageGallery = (productId: number, category?: string, customImages?: string[]): string[] => {
  if (customImages && customImages.length > 0) {
    const valid = customImages.filter(img => img && img.trim().length > 0);
    if (valid.length > 0) return valid;
  }
  const main = getProductImageUrl(productId, category);
  const backup = getProductBackupUrl(productId, category);
  const gallery = [main];
  if (backup && backup !== main) {
    gallery.push(backup);
  }
  return gallery;
};

/**
 * Returns the CDN backup URL for a given product_id
 */
export const getProductBackupUrl = (productId: number, category?: string): string => {
  if (productBackupImages[productId]) {
    return productBackupImages[productId];
  }
  if (category && categoryFallbackImages[category]) {
    return categoryFallbackImages[category];
  }
  return 'https://images.unsplash.com/photo-1505740420928-5e560c06d30e?w=800&auto=format&fit=crop&q=80';
};
